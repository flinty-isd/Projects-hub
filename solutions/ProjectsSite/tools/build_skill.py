"""Build the hpuk-projects-site-lists skill's bundled data from the solutions' list schemas.

The skill must work on its own (uploaded to Claude, or copied to the machine that runs PnP), so it
carries copies of the three project list sets plus a catalogue and a readable reference. This script
writes them, so they always match the schemas the flows are validated against:

  skills/hpuk-projects-site-lists/schemas/pmo.json             EnterprisePMO (10 lists)
  skills/hpuk-projects-site-lists/schemas/controlcentre.json   SharePointControlCentre (6 lists)
  skills/hpuk-projects-site-lists/schemas/board.json           PortalSnapshots, Control Board lists only (5)
  skills/hpuk-projects-site-lists/schemas/catalogue.json       the sets, their overlaps and follow-on steps
  skills/hpuk-projects-site-lists/references/list-sets.md      every list and column, for answering questions

Usage:
  python solutions/ProjectsSite/tools/build_skill.py            # regenerate
  python solutions/ProjectsSite/tools/build_skill.py --check    # CI: fail if out of date
  python solutions/ProjectsSite/tools/build_skill.py --zip DIR  # also write DIR/hpuk-projects-site-lists.zip
"""
import json
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOLUTIONS = ROOT.parent
SKILL = ROOT / "skills" / "hpuk-projects-site-lists"

SETS = {
    "pmo": {
        "title": "Enterprise PMO hub",
        "solution": "EnterprisePMO",
        "filter": None,
        "purpose": "Workstreams, Master RAID Log, Action and Decision Tracker, Change Requests, governance calendar, document libraries and the PMO flows' audit lists.",
        "usedBy": "Enterprise PMO flows 01-05 and the Portfolio-Governance-Hub page.",
        "next": [
            "Run EnterprisePMO/provisioning/Provision-PMOHub.ps1 on the same site for the views, RAG/due-date formatting, hub page and HTML pages (it skips lists that already exist).",
            "Import the EnterprisePMO solution and set PMOSiteUrl to this site.",
        ],
    },
    "controlcentre": {
        "title": "Project Control Centre",
        "solution": "SharePointControlCentre",
        "filter": None,
        "existingOnly": ["SP_MigrationRegister"],
        "purpose": "SP_ lists behind the Project Control Centre pages: migration register, page delivery, actions, RAID, decisions, project updates.",
        "usedBy": "The four Control Centre pages (List and Quick Chart web parts) and the Control Centre Power App.",
        "next": [
            "Apply SharePointControlCentre/sharepoint/column-formatting/DeliveryStatus.json to SP_PageDelivery's Delivery Status column.",
            "Build the four pages per SharePointControlCentre/diagrams/page-layout.md.",
        ],
    },
    "board": {
        "title": "Control Board lists (portal flow P2)",
        "solution": "PortalSnapshots",
        "filter": {"site": "board"},
        "purpose": "Programme Status, Board Decisions, Programme RAID, Migration Waves and Programme Gates for the Project Management Control Board portal.",
        "usedBy": "PortalSnapshots flow P2, which republishes the Control Board page from them.",
        "next": [
            "Set PortalBoardSiteUrl in the PortalSnapshots solution to this site.",
            "Add one Programme Status row before P2's first run.",
        ],
    },
}

# Lists that do the same job in different sets. Creating more than one per group on one site
# gives people two places to record the same thing, so the skill warns before it does.
OVERLAPS = [
    {"role": "RAID log", "lists": {"pmo": "Master RAID Log", "controlcentre": "SP_RAID", "board": "Programme RAID"}},
    {"role": "Decisions", "lists": {"pmo": "Action and Decision Tracker", "controlcentre": "SP_Decisions", "board": "Board Decisions"}},
    {"role": "Actions", "lists": {"pmo": "Action and Decision Tracker", "controlcentre": "SP_Actions"}},
]


def load_set(key, spec):
    schema = json.loads((SOLUTIONS / spec["solution"] / "sharepoint" / "list-schema.json").read_text())
    lists = schema["lists"]
    if spec["filter"]:
        lists = [l for l in lists if all(l.get(k) == v for k, v in spec["filter"].items())]
    out = []
    for l in lists:
        l = {k: v for k, v in l.items() if k not in ("site", "existing")}
        if l["listTitle"] in spec.get("existingOnly", []):
            l["existingOnly"] = True
        out.append(l)
    return {"$comment": f"Generated by ProjectsSite/tools/build_skill.py from {spec['solution']}/sharepoint/list-schema.json. Don't edit: change the source schema and rebuild.",
            "set": key, "lists": out}


TYPE_WORDS = {"Text": "text", "Note": "multi-line text", "Number": "number", "DateTime": "date/time", "Boolean": "yes/no",
              "Choice": "choice", "Person": "person", "Lookup": "lookup", "URL": "link"}


def reference(sets):
    lines = ["# Project list sets", "",
             "<!-- Generated by ProjectsSite/tools/build_skill.py from the solutions' list schemas. Don't edit by hand. -->", "",
             "Three sets of lists can go on the projects site. `scripts/Provision-ProjectLists.ps1 -Sets` takes any of them.", ""]
    lines += ["| Set | Lists | For | Used by |", "|---|---|---|---|"]
    for key, spec in SETS.items():
        lines.append(f"| `{key}` | {len(sets[key]['lists'])} | {spec['purpose']} | {spec['usedBy']} |")
    lines += ["", "## Overlapping lists", "",
              "These do the same job in different sets. Choose one per role where you can; if you create more than one, say which is the master.", "",
              "| Role | " + " | ".join(f"`{k}`" for k in SETS) + " |", "|---|" + "---|" * len(SETS)]
    for o in OVERLAPS:
        lines.append(f"| {o['role']} | " + " | ".join(o["lists"].get(k, "-") for k in SETS) + " |")
    for key, spec in SETS.items():
        lines += ["", f"## `{key}`: {spec['title']}", "", spec["purpose"], "", f"**Used by:** {spec['usedBy']}", "",
                  "**After creating the lists:**", ""] + [f"- {n}" for n in spec["next"]]
        for l in sets[key]["lists"]:
            note = " **Must already exist: checked and missing columns added, never created.**" if l.get("existingOnly") else ""
            lines += ["", f"### {l['listTitle']}", "", f"{l.get('listDescription', '')}{note}", "",
                      "| Column (internal name) | Type | Required | Choices / notes |", "|---|---|---|---|"]
            for f in l["fields"]:
                t = TYPE_WORDS.get(f["type"], f["type"])
                if f["type"] == "Lookup":
                    t += f" to {f['lookupList']}"
                extra = ", ".join(f["choices"]) if f.get("choices") else (f.get("notes") or "")
                if f.get("flowManaged"):
                    extra = ("Written by a flow; hidden from forms. " + extra).strip()
                if f["internalName"] == "Title":
                    t = "built-in Title, renamed"
                lines.append(f"| {f['displayName']} (`{f['internalName']}`) | {t} | {'yes' if f.get('required') else ''} | {extra.replace('|', '/')} |")
    return "\n".join(lines) + "\n"


def outputs():
    sets = {k: load_set(k, s) for k, s in SETS.items()}
    files = {f"schemas/{k}.json": json.dumps(v, indent=2, ensure_ascii=False) + "\n" for k, v in sets.items()}
    files["schemas/catalogue.json"] = json.dumps({
        "$comment": "Generated by ProjectsSite/tools/build_skill.py. Read by scripts/Provision-ProjectLists.ps1 and scripts/plan_lists.py.",
        "sets": {k: {kk: vv for kk, vv in s.items() if kk != "filter"} | {"schema": f"{k}.json"} for k, s in SETS.items()},
        "overlaps": OVERLAPS}, indent=2, ensure_ascii=False) + "\n"
    files["references/list-sets.md"] = reference(sets)
    return files


def main():
    files = outputs()
    if "--check" in sys.argv:
        stale = [p for p, text in files.items() if not (SKILL / p).exists() or (SKILL / p).read_text() != text]
        if stale:
            sys.exit(f"skill data out of date: {stale}: run python solutions/ProjectsSite/tools/build_skill.py")
        print(f"hpuk-projects-site-lists: {len(files)} generated files up to date")
        return
    for p, text in files.items():
        (SKILL / p).parent.mkdir(parents=True, exist_ok=True)
        (SKILL / p).write_text(text)
    print(f"Wrote {len(files)} files under skills/hpuk-projects-site-lists/")
    if "--zip" in sys.argv:
        out = Path(sys.argv[sys.argv.index("--zip") + 1]).resolve()
        out.mkdir(parents=True, exist_ok=True)
        zpath = out / "hpuk-projects-site-lists.zip"
        with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
            for f in sorted(SKILL.rglob("*")):
                if f.is_file() and "__pycache__" not in f.parts:
                    z.write(f, f"hpuk-projects-site-lists/{f.relative_to(SKILL).as_posix()}")
        print(f"Wrote {zpath}")


if __name__ == "__main__":
    main()
